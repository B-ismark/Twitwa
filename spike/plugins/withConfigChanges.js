// Make MainActivity absorb the configuration changes that recreate it.
//
// WHY. `configChanges` in the Expo template lists
// `keyboard|keyboardHidden|orientation|screenSize|screenLayout|uiMode|
// smallestScreenSize|assetsPaths`. A Font size or Display size change
// (`fontScale`, `density`) is not in it, so Android destroys and rebuilds the
// activity while the JS runtime lives on, and the photo picker's launcher
// dies with the old activity. src/recover.js has the measurement. Declaring the
// values here means the activity is told (`onConfigurationChanged`, which RN
// already handles) instead of rebuilt, so the launcher survives. recover.js
// stays as the fallback for any recreation this does not cover.
//
// Only ever ADDS. A value another plugin or the template put there is left
// alone, because removing one turns that change back into a recreation.
//
// WHY A CONFIG PLUGIN. Same reason as plugins/withDebugSuffix.js: android/ is
// generated by `expo prebuild` and is gitignored.

// `uiMode` is already in the template; listed anyway so the plugin states the
// whole set it needs and stays correct if the template drops it.
const WANTED = ['fontScale', 'density', 'uiMode', 'locale', 'layoutDirection'];

const KEY = 'android:configChanges';

/**
 * Add the missing values to one `<activity>` element's attributes. Returns the
 * same object, mutated, so it can run inside the manifest mod. Existing values
 * keep their order and come first.
 */
function apply(activity) {
  if (!activity || !activity.$) {
    throw new Error('withConfigChanges: no <activity> to patch. The manifest shape changed.');
  }
  const have = String(activity.$[KEY] || '')
    .split('|')
    .map((s) => s.trim())
    .filter(Boolean);
  const out = have.slice();
  for (const v of WANTED) if (!out.includes(v)) out.push(v);
  activity.$[KEY] = out.join('|');
  return activity;
}

module.exports = function withConfigChanges(config) {
  const { withAndroidManifest, AndroidConfig } = require('@expo/config-plugins');
  return withAndroidManifest(config, (cfg) => {
    const main = AndroidConfig.Manifest.getMainActivityOrThrow(cfg.modResults);
    apply(main);
    return cfg;
  });
};

// Exported for the test: the plugin itself is only exercisable by a prebuild.
module.exports.apply = apply;
module.exports.WANTED = WANTED;
// Not build.gradle, so the signing suite's chain leaves it out. It has no
// `patch` export either, which is what that chain looks for.
module.exports.target = 'AndroidManifest.xml';
